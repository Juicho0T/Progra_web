-- Esquema aditivo: nunca elimina las tablas del taller original.
CREATE TABLE IF NOT EXISTS rf_meta (clave VARCHAR(80) PRIMARY KEY, valor TEXT NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(120) NOT NULL, correo VARCHAR(160) NOT NULL UNIQUE,
 telefono VARCHAR(30) NOT NULL DEFAULT '', password_hash VARCHAR(255) NOT NULL,
 rol ENUM('cliente','especialista','administrador') NOT NULL DEFAULT 'cliente', activo TINYINT NOT NULL DEFAULT 1,
 creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_consoles (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, cliente_id INT UNSIGNED NOT NULL, tipo VARCHAR(60) NOT NULL,
 marca VARCHAR(80) NOT NULL, modelo VARCHAR(100) NOT NULL, serie VARCHAR(100) NOT NULL DEFAULT '', condicion TEXT NOT NULL,
 FOREIGN KEY(cliente_id) REFERENCES rf_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_repairs (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, cliente_id INT UNSIGNED NOT NULL, consola_id INT UNSIGNED NOT NULL,
 tecnico_id INT UNSIGNED NULL, servicio VARCHAR(100) NOT NULL, falla TEXT NOT NULL, foto VARCHAR(120) NULL,
 estado VARCHAR(30) NOT NULL DEFAULT 'recibida', diagnostico TEXT NULL, trabajo TEXT NULL, piezas TEXT NULL,
 creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, actualizado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(cliente_id) REFERENCES rf_users(id), FOREIGN KEY(consola_id) REFERENCES rf_consoles(id), FOREIGN KEY(tecnico_id) REFERENCES rf_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_quotes (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, reparacion_id INT UNSIGNED NOT NULL, administrador_id INT UNSIGNED NOT NULL,
 version INT NOT NULL, diagnostico TEXT NOT NULL, conceptos TEXT NOT NULL, mano_obra INT UNSIGNED NOT NULL, refacciones INT UNSIGNED NOT NULL,
 total INT UNSIGNED NOT NULL, vence DATE NOT NULL, estado VARCHAR(25) NOT NULL DEFAULT 'pendiente', decidido DATETIME NULL,
 creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(reparacion_id,version),
 FOREIGN KEY(reparacion_id) REFERENCES rf_repairs(id), FOREIGN KEY(administrador_id) REFERENCES rf_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_appointments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, reparacion_id INT UNSIGNED NOT NULL, fecha DATETIME NOT NULL,
 tipo VARCHAR(25) NOT NULL, notas VARCHAR(500) NOT NULL DEFAULT '', estado VARCHAR(25) NOT NULL DEFAULT 'programada',
 FOREIGN KEY(reparacion_id) REFERENCES rf_repairs(id), INDEX(fecha)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_history (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, reparacion_id INT UNSIGNED NOT NULL, autor_id INT UNSIGNED NOT NULL,
 anterior VARCHAR(30) NOT NULL, nuevo VARCHAR(30) NOT NULL, comentario TEXT NOT NULL, creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(reparacion_id) REFERENCES rf_repairs(id), FOREIGN KEY(autor_id) REFERENCES rf_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_products (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, sku VARCHAR(60) NOT NULL UNIQUE, titulo VARCHAR(150) NOT NULL,
 plataforma VARCHAR(50) NOT NULL, formato VARCHAR(30) NOT NULL DEFAULT 'Físico', condicion VARCHAR(150) NOT NULL,
 descripcion TEXT NOT NULL, precio INT UNSIGNED NOT NULL, stock INT UNSIGNED NOT NULL DEFAULT 0,
 arte VARCHAR(30) NOT NULL DEFAULT 'orbit', activo TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_orders (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, cliente_id INT UNSIGNED NOT NULL, total INT UNSIGNED NOT NULL,
 estado VARCHAR(25) NOT NULL DEFAULT 'confirmado', token VARCHAR(80) NOT NULL UNIQUE,
 creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, entregado DATETIME NULL,
 FOREIGN KEY(cliente_id) REFERENCES rf_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_order_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, pedido_id INT UNSIGNED NOT NULL, producto_id INT UNSIGNED NOT NULL,
 titulo VARCHAR(150) NOT NULL, plataforma VARCHAR(50) NOT NULL, condicion VARCHAR(150) NOT NULL,
 cantidad INT UNSIGNED NOT NULL, precio INT UNSIGNED NOT NULL, UNIQUE(pedido_id,producto_id),
 FOREIGN KEY(pedido_id) REFERENCES rf_orders(id), FOREIGN KEY(producto_id) REFERENCES rf_products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_offers (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, cliente_id INT UNSIGNED NOT NULL, titulo VARCHAR(150) NOT NULL,
 plataforma VARCHAR(50) NOT NULL, condicion TEXT NOT NULL, foto VARCHAR(120) NULL, importe INT UNSIGNED NULL,
 notas TEXT NULL, estado VARCHAR(25) NOT NULL DEFAULT 'pendiente', producto_id INT UNSIGNED NULL,
 creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, aceptado DATETIME NULL, recibido DATETIME NULL,
 FOREIGN KEY(cliente_id) REFERENCES rf_users(id), FOREIGN KEY(producto_id) REFERENCES rf_products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_plans (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, plataforma ENUM('Xbox','PlayStation') NOT NULL,
 nombre VARCHAR(100) NOT NULL, duracion VARCHAR(40) NOT NULL, region VARCHAR(60) NOT NULL,
 precio INT UNSIGNED NOT NULL, descripcion TEXT NOT NULL, disponible TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_subscriptions (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, cliente_id INT UNSIGNED NOT NULL, plan_id INT UNSIGNED NOT NULL,
 plataforma VARCHAR(30) NOT NULL, nombre VARCHAR(100) NOT NULL, duracion VARCHAR(40) NOT NULL, region VARCHAR(60) NOT NULL,
 total INT UNSIGNED NOT NULL, estado VARCHAR(25) NOT NULL DEFAULT 'confirmada', referencia VARCHAR(100) NULL,
 inicio DATE NULL, fin DATE NULL, anterior_id INT UNSIGNED NULL, token VARCHAR(80) NOT NULL UNIQUE,
 creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, entregado DATETIME NULL,
 FOREIGN KEY(cliente_id) REFERENCES rf_users(id), FOREIGN KEY(plan_id) REFERENCES rf_plans(id), FOREIGN KEY(anterior_id) REFERENCES rf_subscriptions(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_payments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, reparacion_id INT UNSIGNED NULL, pedido_id INT UNSIGNED NULL,
 suscripcion_id INT UNSIGNED NULL, oferta_id INT UNSIGNED NULL, autor_id INT UNSIGNED NOT NULL,
 total INT UNSIGNED NOT NULL, metodo VARCHAR(30) NOT NULL, referencia VARCHAR(100) NOT NULL,
 estado VARCHAR(25) NOT NULL DEFAULT 'pagado', creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(reparacion_id), UNIQUE(pedido_id), UNIQUE(suscripcion_id), UNIQUE(oferta_id),
 FOREIGN KEY(reparacion_id) REFERENCES rf_repairs(id), FOREIGN KEY(pedido_id) REFERENCES rf_orders(id),
 FOREIGN KEY(suscripcion_id) REFERENCES rf_subscriptions(id), FOREIGN KEY(oferta_id) REFERENCES rf_offers(id),
 FOREIGN KEY(autor_id) REFERENCES rf_users(id),
 CHECK ((reparacion_id IS NOT NULL)+(pedido_id IS NOT NULL)+(suscripcion_id IS NOT NULL)+(oferta_id IS NOT NULL)=1)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_receipts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, pago_id INT UNSIGNED NOT NULL UNIQUE, creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(pago_id) REFERENCES rf_payments(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_reviews (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, reparacion_id INT UNSIGNED NOT NULL UNIQUE, cliente_id INT UNSIGNED NOT NULL,
 estrellas TINYINT NOT NULL, comentario TEXT NOT NULL, creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(reparacion_id) REFERENCES rf_repairs(id), FOREIGN KEY(cliente_id) REFERENCES rf_users(id), CHECK(estrellas BETWEEN 1 AND 5)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_audit (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, autor_id INT UNSIGNED NOT NULL, tipo VARCHAR(30) NOT NULL,
 referencia_id INT UNSIGNED NOT NULL, accion VARCHAR(80) NOT NULL, detalle TEXT NOT NULL, creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(autor_id) REFERENCES rf_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rf_stock (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, producto_id INT UNSIGNED NOT NULL, autor_id INT UNSIGNED NOT NULL,
 cantidad INT NOT NULL, motivo VARCHAR(120) NOT NULL, creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(producto_id) REFERENCES rf_products(id), FOREIGN KEY(autor_id) REFERENCES rf_users(id)
) ENGINE=InnoDB;
